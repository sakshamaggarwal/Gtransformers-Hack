"""
Build the knowledge base the chat app reads.

    python pipeline/build_kb.py

Steps
  1. INGEST    every data/raw/{wapo,reddit}/*.json (parser output), flattening
               comments + replies into one list of items
  2. CLEAN     collapse whitespace, mask emails / phone numbers
  3. FILTER    keep only health-relevant items (tagged with >= 1 topic)
  4. SCORE     trust score + label + explainable signals (trust.py)
  5. EXTRACT   actionable tips per item
  6. EMIT      netlify/lib/knowledge/community.mjs   (scored community items)
               netlify/lib/knowledge/ayurveda.mjs    (from knowledge/ayurveda.json)
               netlify/lib/knowledge/clinical.mjs    (from knowledge/clinical.json)
               netlify/lib/knowledge/topics.mjs      (taxonomy, for query routing)
               data/processed/community_scored.json  (everything, incl. rejected, for review)
"""

import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from taxonomy import TOPICS, tag_topics  # noqa: E402
from trust import extract_tips, trust_score  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
OUT_JS = ROOT / "netlify" / "lib" / "knowledge"
OUT_DATA = ROOT / "data" / "processed"
SOURCE_LABEL = {"wapo": "Washington Post comments", "reddit": "Reddit"}

EMAIL = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
PHONE = re.compile(r"(?:\+?\d{1,2}[ .-]?)?\(?\b\d{3}\)?[ .-]?\d{3}[ .-]?\d{4}\b")


def clean(text):
    text = re.sub(r"\s+", " ", text or "").strip()
    return PHONE.sub("[PHONE]", EMAIL.sub("[EMAIL]", text))


def flatten(payload, path):
    """Parser output -> flat list of items (comment, then its replies)."""
    threads = payload["threads"] if isinstance(payload, dict) else payload  # old parser wrote a bare list
    meta = payload if isinstance(payload, dict) else {"source": "wapo", "url": "", "title": path.stem}
    for t in threads:
        for i, c in enumerate([t] + t.get("replies", [])):
            yield {
                "source": meta.get("source", "wapo"),
                "source_title": meta.get("title") or path.stem,
                "url": c.get("url") or t.get("url") or meta.get("url", ""),
                "synthetic": bool(meta.get("synthetic", False)),
                "external_id": c.get("id"),
                "parent_id": None if i == 0 else t.get("id"),
                "author": c.get("author", ""),
                "author_flair": c.get("author_flair", ""),
                "date": (c.get("timestamp") or "")[:10],
                "text": clean(c.get("text", "")),
                "upvotes": int(c.get("upvotes", 0) or 0),
                "downvotes": int(c.get("downvotes", 0) or 0),
                "reactions": c.get("reactions", 0) if isinstance(c.get("reactions"), int)
                else sum(r.get("count", 0) for r in c.get("reactions", [])),
            }


def to_module(name, data, comment):
    body = json.dumps(data, indent=1, ensure_ascii=False)
    return f"// {name}: GENERATED by pipeline/build_kb.py. Do not edit by hand.\n// {comment}\nexport default {body};\n"


def main():
    items = []
    for path in sorted(RAW.glob("*/*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        batch = list(flatten(payload, path))
        print(f"  ingest {path.relative_to(ROOT)}: {len(batch)} comments")
        items.extend(batch)

    scored, seen, thread_topics = [], set(), {}
    for it in items:
        key = it["text"][:120].lower()
        if not it["text"] or key in seen:  # drop empties and duplicates
            continue
        seen.add(key)
        topics = tag_topics(it["text"])
        if it["parent_id"] is None:
            thread_topics[it["external_id"]] = topics
        elif not topics and len(it["text"].split()) >= 12:
            # a reply inherits its thread's topic ("This matched my experience...")
            topics = thread_topics.get(it["parent_id"], [])
        if not topics:
            it.update(topics=[], trust=0, label="off_topic", signals=["not health-related"])
        else:
            score, label, signals = trust_score(it, topics)
            it.update(topics=topics, trust=score, label=label, signals=signals, tips=extract_tips(it["text"]))
        scored.append(it)

    scored.sort(key=lambda x: -x["trust"])
    usable = [x for x in scored if x["label"] in ("trusted", "review")]
    community = []
    for n, x in enumerate(usable, 1):
        community.append({
            "id": f"C{n}", "source": x["source"], "source_label": SOURCE_LABEL.get(x["source"], x["source"]),
            "source_title": x["source_title"], "url": x["url"], "synthetic": x["synthetic"],
            "author": x["author"], "date": x["date"], "upvotes": x["upvotes"], "is_reply": bool(x["parent_id"]),
            "topics": x["topics"], "trust": x["trust"], "label": x["label"], "signals": x["signals"],
            "tips": x.get("tips", []), "text": x["text"][:900],
        })

    OUT_DATA.mkdir(parents=True, exist_ok=True)
    (OUT_DATA / "community_scored.json").write_text(json.dumps(scored, indent=2, ensure_ascii=False), encoding="utf-8")

    ayurveda = json.loads((ROOT / "knowledge" / "ayurveda.json").read_text(encoding="utf-8"))
    clinical = json.loads((ROOT / "knowledge" / "clinical.json").read_text(encoding="utf-8"))
    topics = {k: {"label": v["label"], "condition": v["condition"], "keywords": v["keywords"]} for k, v in TOPICS.items()}

    OUT_JS.mkdir(parents=True, exist_ok=True)
    (OUT_JS / "community.mjs").write_text(to_module("community.mjs", community,
        "Health-relevant community comments with trust scores (trusted + review only)."), encoding="utf-8")
    (OUT_JS / "ayurveda.mjs").write_text(to_module("ayurveda.mjs", ayurveda,
        "Curated ayurvedic remedies per topic, with evidence level and cautions. Source: knowledge/ayurveda.json"), encoding="utf-8")
    (OUT_JS / "clinical.mjs").write_text(to_module("clinical.mjs", clinical,
        "Evidence-based reference facts per topic. Source: knowledge/clinical.json"), encoding="utf-8")
    (OUT_JS / "topics.mjs").write_text(to_module("topics.mjs", topics,
        "Health topic taxonomy. Source: pipeline/taxonomy.py"), encoding="utf-8")

    labels = Counter(x["label"] for x in scored)
    by_topic = Counter(t for x in community for t in x["topics"])
    print(f"\n{len(items)} comments ingested -> {len(scored)} unique")
    print("labels: " + ", ".join(f"{k}={v}" for k, v in labels.most_common()))
    print("usable by topic: " + ", ".join(f"{k}={v}" for k, v in by_topic.most_common()))
    print(f"ayurveda entries: {len(ayurveda)}, clinical entries: {len(clinical)}")
    print(f"wrote {OUT_JS.relative_to(ROOT)}/{{community,ayurveda,clinical,topics}}.mjs")


if __name__ == "__main__":
    main()
